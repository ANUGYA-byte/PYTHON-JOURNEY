# ---------------------------------------

number = int(input("Enter Number: "))

if number % 2 == 0:
    print(number,"Number is Even")
else:
    print(number,"Number is Odd")

# ---------------------------------------
# SAMPLE -
# Enter Number: 33
# 33.0 Number is Odd 

