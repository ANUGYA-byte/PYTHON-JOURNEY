# Program 17: Area of Triangle
# Description: Calculates the area of a triangle using base and height.
# Author: Anugya Agrawal
# ---------------------------------------

base = float(input("Enter Base: "))
height = float(input("Enter Height: "))

area_of_triangle = 0.5 * base * height

print("Area of triangle:", area_of_triangle)

# ---------------------------------------
# SAMPLE INPUT
# Enter Base: 12
# Enter Height: 33
# ---------------------------------------

# SAMPLE OUTPUT
# Area of triangle: 198.0
